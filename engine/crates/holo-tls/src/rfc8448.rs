const fn hex_val(c: u8) -> u8 {
    match c {
        b'0'..=b'9' => c - b'0',
        b'a'..=b'f' => c - b'a' + 10,
        b'A'..=b'F' => c - b'A' + 10,
        _ => panic!("invalid hex digit"),
    }
}

/// Parse hex-with-spaces (RFC 8448 layout) into a Vec<u8>, runtime.
pub(crate) fn hex(s: &str) -> Vec<u8> {
    let bytes = s.as_bytes();
    let mut out = Vec::with_capacity(bytes.len() / 2 + 1);
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b' ' {
            i += 1;
            continue;
        }
        assert!(i + 1 < bytes.len(), "odd hex length");
        out.push((hex_val(bytes[i]) << 4) | hex_val(bytes[i + 1]));
        i += 2;
    }
    out
}

/// Parse hex-with-spaces into exactly 32 bytes, const-time (no allocation).
pub(crate) const fn dehex32(s: &str) -> [u8; 32] {
    let bytes = s.as_bytes();
    let mut a = [0u8; 32];
    let mut idx = 0;
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b' ' {
            i += 1;
            continue;
        }
        a[idx] = (hex_val(bytes[i]) << 4) | hex_val(bytes[i + 1]);
        idx += 1;
        i += 2;
    }
    if idx != 32 {
        panic!("expected exactly 32 bytes");
    }
    a
}
